"""Reproduce an unsuccessful fixed-shape SenseVoice specialization experiment.

The published MIL arithmetic and weight bytes are preserved. A small public MIL
program supplies correctly compiled fixed I/O metadata; its body is then replaced
by the pinned SenseVoice body with a fixed input shape. These remain research
assets: they load but still return NaNs on the development host. This script is
retained for diagnosis, not as a working model acquisition or conversion path.
"""

import hashlib
import json
import os
import shutil
from pathlib import Path

import coremltools as ct
import numpy as np
from coremltools.converters.mil import Builder as mb
from coremltools.converters.mil.mil import types


def metadata_program_for(bucket):
    @mb.program(
        input_specs=[
            mb.TensorSpec(shape=(1,), dtype=types.int32),
            mb.TensorSpec(shape=(1, bucket, 560), dtype=types.fp32),
            mb.TensorSpec(shape=(1,), dtype=types.int32),
            mb.TensorSpec(shape=(1,), dtype=types.int32),
        ],
        opset_version=ct.target.iOS17,
    )
    def metadata_program(language, speech, speech_lengths, textnorm):
        controls = mb.add(x=language, y=mb.add(x=speech_lengths, y=textnorm))
        data = mb.add(x=speech, y=mb.cast(x=controls, dtype="fp32"))
        padded = mb.concat(values=[np.zeros((1, 4, 560), np.float32), data], axis=1)
        repeated = mb.tile(x=padded, reps=[1, 1, 45])
        sliced = mb.slice_by_index(
            x=repeated, begin=[0, 0, 0], end=[1, bucket + 4, 25055]
        )
        return mb.cast(x=sliced, dtype="fp16", name="ctc_logits")

    return metadata_program


def main():
    root = Path("artifacts/drafts/sensevoice-small/models")
    source = root / "SenseVoiceSmall_int8.mlmodelc"
    original = (source / "model.mil").read_text()
    metadata_root = root / "specialization-metadata"
    metadata_root.mkdir(exist_ok=True)
    for bucket in (128, 256, 512):
        destination = root / f"SenseVoiceSmall_int8_fixed{bucket}.mlmodelc"
        if destination.exists():
            raise FileExistsError(destination)

        model = ct.convert(
            metadata_program_for(bucket),
            convert_to="mlprogram",
            minimum_deployment_target=ct.target.macOS14,
            compute_units=ct.ComputeUnit.CPU_AND_NE,
            skip_model_load=True,
        )
        package = metadata_root / f"t{bucket}.mlpackage"
        model.save(str(package))
        ct.models.utils.compile_model(str(package), destination_path=str(destination))
        lines = original.splitlines()
        if "[FlexibleShapeInformation" not in lines[3]:
            raise ValueError("Unexpected pinned MIL function declaration")
        lines[3] = (
            lines[3]
            .split(" [FlexibleShapeInformation")[0]
            .replace(
                "tensor<fp32, [1, ?, 560]> speech",
                f"tensor<fp32, [1, {bucket}, 560]> speech",
            )
            + " {"
        )
        program = "\n".join(lines) + "\n"
        (destination / "model.mil").write_text(program)
        weights = destination / "weights"
        if weights.exists():
            shutil.rmtree(weights)
        weights.mkdir()
        for path in (source / "weights").iterdir():
            if not path.is_file():
                raise ValueError("Unexpected nested weight resource")
            os.link(path, weights / path.name)
        record = {
            "bucket": bucket,
            "source_mil_sha256": hashlib.sha256(original.encode()).hexdigest(),
            "specialized_mil_sha256": hashlib.sha256(program.encode()).hexdigest(),
            "weights_modified": False,
            "io_metadata": "generated by local Core ML compiler from exact fixed interface",
        }
        (destination / "specialization.json").write_text(
            json.dumps(record, indent=2) + "\n"
        )
        print(json.dumps(record), flush=True)


if __name__ == "__main__":
    main()
